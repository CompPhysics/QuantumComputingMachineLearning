"""Build the Jupyter Book of "Quantum Computing for Many-body Physics".

    cd doc/Book/Notebooks
    python3 build_book.py                 # merge the bibliographies, check the table of contents, build the HTML
    python3 build_book.py --regenerate    # first regenerate every notebook of _toc.yml from the LaTeX
    python3 build_book.py --execute       # re-execute all notebooks during the build (about ten minutes)
    python3 build_book.py --clean         # remove _build first
    python3 build_book.py --check         # everything except the build itself (no jupyter-book needed)

The book is the set of generated chapter notebooks chapterN/chapterN.ipynb
(see README.md; never edit them by hand) plus intro.md and references.md.
Three things are prepared before ``jupyter-book build .`` is called:

1. references.bib is merged from ../chapter*.bib.  The chapter files repeat
   entries that several chapters cite; sphinxcontrib-bibtex refuses duplicate
   keys, so the first occurrence is kept and a differing repeat is reported.
2. Every file of _toc.yml must exist, and every chapter notebook that exists
   must be in _toc.yml (a commented-out entry is reported, not an error).
3. Every figure a notebook refers to (../../BookFigures/chapterN/*.png) must
   exist; run the chapter programs and BookPrograms/render_tikz.py if not.

Only the standard library is needed for the preparation; the build needs the
packages of requirements.txt.
"""
import argparse, json, pathlib, re, shutil, subprocess, sys

HERE = pathlib.Path(__file__).resolve().parent            # doc/Book/Notebooks
BOOK = HERE.parent                                        # doc/Book


def split_bib(text):
    """Yield (key, entry) for every @type{key, ...} of a BibTeX file, by brace counting."""
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", text):
        if m.group(1).lower() in ("comment", "string", "preamble"):
            continue
        depth, i = 0, m.start()
        while i < len(text):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        yield m.group(2), text[m.start():i + 1]


def merge_bibliographies():
    entries, origin, clashes = {}, {}, []
    files = sorted(BOOK.glob("chapter*.bib"), key=lambda p: int(re.sub(r"\D", "", p.stem) or 0))
    for bib in files:
        for key, entry in split_bib(bib.read_text(encoding="utf-8")):
            if key in entries:
                if re.sub(r"\s+", "", entry) != re.sub(r"\s+", "", entries[key]):
                    clashes.append(f"{key}: {bib.name} differs from {origin[key]} (kept {origin[key]})")
                continue
            entries[key], origin[key] = entry, bib.name
    header = ("% Generated by build_book.py from " + ", ".join(b.name for b in files)
              + " -- do not edit; edit the chapter .bib files.\n\n")
    (HERE / "references.bib").write_text(header + "\n\n".join(entries[k] for k in sorted(entries, key=str.lower)) + "\n",
                                         encoding="utf-8")
    print(f"references.bib: {len(entries)} entries from {len(files)} files")
    for c in clashes:
        print("  note, duplicate key with different text --", c)
    return entries


def toc_files():
    text = (HERE / "_toc.yml").read_text(encoding="utf-8")
    active = re.findall(r"^\s*-?\s*(?:file|root):\s*(\S+)", text, flags=re.M)
    commented = re.findall(r"^\s*#\s*-\s*file:\s*(\S+)", text, flags=re.M)
    return active, commented


def resolve(name):
    for ext in ("", ".ipynb", ".md"):
        p = HERE / (name + ext)
        if p.is_file():
            return p
    return None


def check(entries):
    ok = True
    active, commented = toc_files()
    for name in active:
        if resolve(name) is None:
            print(f"MISSING: _toc.yml lists {name} but there is no such notebook or page"); ok = False
    listed = {str(resolve(n)) for n in active if resolve(n)}
    for nb in sorted(HERE.glob("chapter*/chapter*.ipynb")):
        rel = nb.relative_to(HERE).with_suffix("").as_posix()
        if str(nb) not in listed:
            where = "commented out in" if rel in commented else "absent from"
            print(f"note: {rel}.ipynb exists but is {where} _toc.yml")
    cited = set()
    for name in active:
        p = resolve(name)
        if p is None or p.suffix != ".ipynb":
            continue
        nb = json.loads(p.read_text(encoding="utf-8"))
        md = "\n".join("".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "markdown")
        for img in re.findall(r"!\[[^\]]*\]\(([^)\s]+)\)", md):
            if not img.startswith("http") and not (p.parent / img).resolve().is_file():
                print(f"MISSING figure in {p.name}: {img}"); ok = False
        for group in re.findall(r"\[([A-Za-z][\w:.+-]*\d{4}\w*(?:,\s*[A-Za-z][\w:.+-]*\d{4}\w*)*)\]", md):
            cited.update(k.strip() for k in group.split(","))
        n_code = sum(c["cell_type"] == "code" for c in nb["cells"])
        n_out = sum(c["cell_type"] == "code" and bool(c.get("outputs")) for c in nb["cells"])
        if n_code > 1 and n_out == 0:
            print(f"note: {p.name} has no stored outputs; execute it (README.md) or build with --execute")
    unknown = sorted(k for k in cited if k not in entries)
    if unknown:
        print("note: cited in the notebooks but in no chapter .bib file:", ", ".join(unknown))
    return ok


def regenerate():
    active, _ = toc_files()
    numbers = sorted({int(m.group(1)) for n in active if (m := re.match(r"chapter(\d+)/", n))})
    cmd = [sys.executable, str(BOOK / "BookPrograms" / "tex_to_notebook.py"), str(HERE), ",".join(map(str, numbers))]
    print(" ".join(cmd)); subprocess.check_call(cmd, cwd=BOOK)
    print("The regenerated notebooks have no outputs: execute them (README.md) or build with --execute.")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--regenerate", action="store_true", help="regenerate the notebooks of _toc.yml from the LaTeX first")
    ap.add_argument("--execute", action="store_true", help="re-execute every notebook during the build")
    ap.add_argument("--clean", action="store_true", help="remove _build before building")
    ap.add_argument("--check", action="store_true", help="prepare and check only, do not build")
    args = ap.parse_args()

    if args.regenerate:
        regenerate()
    good = check(merge_bibliographies())
    if not good:
        sys.exit("Fix the problems above before building.")
    if args.check:
        sys.exit(0)
    if args.clean and (HERE / "_build").exists():
        shutil.rmtree(HERE / "_build")
    exe = shutil.which("jupyter-book") or shutil.which("jb")
    if exe is None:
        sys.exit("jupyter-book is not installed:  pip install -r requirements.txt")
    version = subprocess.run([exe, "--version"], capture_output=True, text=True).stdout
    m = re.search(r"Jupyter Book\s*:\s*(\d+)", version) or re.search(r"(\d+)\.\d+", version)
    if m and int(m.group(1)) >= 2:
        sys.exit("This book is configured for Jupyter Book 1.x (_config.yml, _toc.yml):  pip install -r requirements.txt")
    cmd = [exe, "build", str(HERE)]
    if args.execute:
        cmd += ["--config", str(HERE / "_config_execute.yml")]
        cfg = (HERE / "_config.yml").read_text(encoding="utf-8").replace('execute_notebooks: "off"', 'execute_notebooks: "force"')
        (HERE / "_config_execute.yml").write_text(cfg, encoding="utf-8")
    print(" ".join(cmd))
    code = subprocess.call(cmd)
    if code == 0:
        print(f"\nOpen {HERE / '_build' / 'html' / 'index.html'}")
    sys.exit(code)
